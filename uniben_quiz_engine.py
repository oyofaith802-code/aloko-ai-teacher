import json
import os
import random
import time
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

FREE_QUESTIONS = 12
FREE_DURATION_SECONDS = 5 * 60
PREMIUM_QUESTIONS = 25
PREMIUM_DURATION_SECONDS = 10 * 60
PREMIUM_ACCESS_SECONDS = 5 * 60 * 60


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured.")
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_quiz_tables():
    """Create separate tables without changing existing HND tables."""
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS uniben_quiz_questions (
                id BIGSERIAL PRIMARY KEY,
                course TEXT NOT NULL,
                question_text TEXT NOT NULL,
                options JSONB NOT NULL,
                correct_option TEXT,
                explanation TEXT,
                source_page INTEGER,
                source_session TEXT,
                question_origin TEXT NOT NULL DEFAULT 'past_question',
                verified BOOLEAN NOT NULL DEFAULT FALSE,
                active BOOLEAN NOT NULL DEFAULT FALSE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS uniben_quiz_attempts (
                id UUID PRIMARY KEY,
                student_id TEXT NOT NULL,
                course TEXT NOT NULL,
                tier TEXT NOT NULL CHECK (tier IN ('free', 'premium')),
                started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                expires_at TIMESTAMPTZ NOT NULL,
                question_ids JSONB NOT NULL,
                answers JSONB NOT NULL DEFAULT '{}'::jsonb,
                status TEXT NOT NULL DEFAULT 'in_progress'
                    CHECK (status IN ('in_progress', 'submitted', 'expired')),
                score INTEGER,
                submitted_at TIMESTAMPTZ
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS uniben_quiz_free_usage (
                student_id TEXT PRIMARY KEY,
                used_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS uniben_quiz_premium_access (
                id BIGSERIAL PRIMARY KEY,
                student_id TEXT NOT NULL,
                payment_reference TEXT UNIQUE NOT NULL,
                expires_at TIMESTAMPTZ NOT NULL,
                verified_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_uniben_quiz_course_active
            ON uniben_quiz_questions(course, active, verified)
        """)


def get_verified_questions(course, limit):
    """Never return unverified or inactive questions."""
    with get_connection() as conn:
        return conn.execute("""
            SELECT id, course, question_text, options, source_page,
                   source_session, question_origin
            FROM uniben_quiz_questions
            WHERE course = %s
              AND verified = TRUE
              AND active = TRUE
            ORDER BY RANDOM()
            LIMIT %s
        """, (course, limit)).fetchall()


def premium_is_active(student_id):
    with get_connection() as conn:
        row = conn.execute("""
            SELECT EXISTS (
                SELECT 1
                FROM uniben_quiz_premium_access
                WHERE student_id = %s
                  AND expires_at > NOW()
            ) AS active
        """, (student_id,)).fetchone()
    return bool(row["active"])


def start_quiz(student_id, course, attempt_id, premium=False):
    """
    attempt_id must be a UUID generated by the caller.
    Free usage is reserved transactionally to prevent repeated attempts.
    Premium access must already have been verified through a trusted
    payment-verification flow before this function is called.
    """
    import uuid

    try:
        attempt_id = str(uuid.UUID(str(attempt_id)))
    except ValueError:
        raise ValueError("attempt_id must be a valid UUID.")

    if not student_id or not course:
        raise ValueError("Student ID and course are required.")

    tier = "premium" if premium else "free"
    count = PREMIUM_QUESTIONS if premium else FREE_QUESTIONS
    duration = PREMIUM_DURATION_SECONDS if premium else FREE_DURATION_SECONDS

    with get_connection() as conn:
        if premium:
            active = conn.execute("""
                SELECT EXISTS (
                    SELECT 1 FROM uniben_quiz_premium_access
                    WHERE student_id = %s AND expires_at > NOW()
                ) AS active
            """, (student_id,)).fetchone()["active"]
            if not active:
                raise PermissionError("No active premium access.")
        else:
            conn.execute("""
                INSERT INTO uniben_quiz_free_usage(student_id)
                VALUES (%s)
                ON CONFLICT (student_id) DO NOTHING
            """, (student_id,))
            inserted = conn.execute("SELECT 1").fetchone()
            # The insertion result is checked below using the command tag.
            # Use a transaction-level lock for consistent free-use checking.
            usage = conn.execute("""
                SELECT student_id FROM uniben_quiz_free_usage
                WHERE student_id = %s FOR UPDATE
            """, (student_id,)).fetchone()
            existing_attempt = conn.execute("""
                SELECT id FROM uniben_quiz_attempts
                WHERE student_id = %s AND tier = 'free'
                LIMIT 1
            """, (student_id,)).fetchone()
            if existing_attempt:
                raise PermissionError("The free quiz has already been used.")

        questions = conn.execute("""
            SELECT id, course
            FROM uniben_quiz_questions
            WHERE course = %s AND verified = TRUE AND active = TRUE
            ORDER BY RANDOM()
            LIMIT %s
        """, (course, count)).fetchall()

        if len(questions) < count:
            raise ValueError(
                f"Not enough verified questions for {course}. "
                f"Need {count}; found {len(questions)}."
            )

        ids = [str(q["id"]) for q in questions]
        conn.execute("""
            INSERT INTO uniben_quiz_attempts
                (id, student_id, course, tier, expires_at, question_ids)
            VALUES (%s, %s, %s, %s, NOW() + (%s * INTERVAL '1 second'), %s)
        """, (attempt_id, student_id, course, tier, duration, json.dumps(ids)))

    return {
        "attempt_id": attempt_id,
        "course": course,
        "tier": tier,
        "question_count": count,
        "duration_seconds": duration,
        "status": "in_progress",
    }


def get_attempt(attempt_id, student_id):
    with get_connection() as conn:
        attempt = conn.execute("""
            SELECT id, student_id, course, tier, started_at, expires_at,
                   question_ids, answers, status, score
            FROM uniben_quiz_attempts
            WHERE id = %s AND student_id = %s
        """, (attempt_id, student_id)).fetchone()

        if not attempt:
            raise LookupError("Quiz attempt not found.")

        if attempt["status"] == "in_progress":
            expired = conn.execute("""
                UPDATE uniben_quiz_attempts
                SET status = 'expired'
                WHERE id = %s AND expires_at <= NOW()
                  AND status = 'in_progress'
                RETURNING id
            """, (attempt_id,)).fetchone()
            if expired:
                attempt["status"] = "expired"

        return attempt


def submit_quiz(attempt_id, student_id, answers):
    """
    answers: dictionary mapping question ID strings to selected option keys.
    The correct answers are scored only on the server.
    """
    with get_connection() as conn:
        attempt = conn.execute("""
            SELECT * FROM uniben_quiz_attempts
            WHERE id = %s AND student_id = %s
            FOR UPDATE
        """, (attempt_id, student_id)).fetchone()

        if not attempt:
            raise LookupError("Quiz attempt not found.")
        if attempt["status"] != "in_progress":
            raise ValueError("This quiz is no longer active.")

        if conn.execute("""
            SELECT NOW() >= expires_at AS expired
            FROM uniben_quiz_attempts WHERE id = %s
        """, (attempt_id,)).fetchone()["expired"]:
            conn.execute("""
                UPDATE uniben_quiz_attempts SET status = 'expired'
                WHERE id = %s
            """, (attempt_id,))
            raise TimeoutError("The quiz time has expired.")

        question_ids = [int(qid) for qid in attempt["question_ids"]]
        allowed_ids = {str(qid) for qid in question_ids}
        safe_answers = {
            str(qid): str(option)
            for qid, option in answers.items()
            if str(qid) in allowed_ids and isinstance(option, str)
        }

        correct = conn.execute("""
            SELECT id, correct_option
            FROM uniben_quiz_questions
            WHERE id = ANY(%s)
              AND verified = TRUE AND active = TRUE
        """, (question_ids,)).fetchall()

        correct_map = {str(q["id"]): q["correct_option"] for q in correct}
        score = sum(
            1 for qid, option in safe_answers.items()
            if correct_map.get(qid) is not None
            and option == correct_map[qid]
        )

        conn.execute("""
            UPDATE uniben_quiz_attempts
            SET answers = %s, score = %s, status = 'submitted',
                submitted_at = NOW()
            WHERE id = %s
        """, (json.dumps(safe_answers), score, attempt_id))

    return {
        "attempt_id": str(attempt_id),
        "score": score,
        "total_questions": len(question_ids),
        "status": "submitted",
    }
